namespace Testo.UI.Shared.Components;

/// <summary>How large a button is drawn.</summary>
public enum ButtonSize
{
    /// <summary>32px. Dense UI: table rows, toolbars.</summary>
    Small,

    /// <summary>40px. The default, and the comfortable target size for the public site.</summary>
    Medium,

    /// <summary>48px. A single prominent action, such as a hero call to action.</summary>
    Large,
}
