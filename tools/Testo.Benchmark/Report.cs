using System.Globalization;
using System.Text;
using Testo.Contracts.Planning;

namespace Testo.Benchmark;

/// <summary>
/// Turns measurements into the table ADR-0019 §7 asks for.
/// </summary>
/// <remarks>
/// It reports the mistakes before the successes, and it reports the baseline beside the planner
/// rather than alone, because a pass rate with nothing to compare it to is a number that can be
/// made to mean anything.
/// </remarks>
public static class Report
{
    /// <summary>The whole report, as markdown.</summary>
    public static string Write(IReadOnlyList<Measurement> measurements, int repetitions, DateTimeOffset when)
    {
        ArgumentNullException.ThrowIfNull(measurements);

        var text = new StringBuilder();
        var sources = measurements.Select(measurement => measurement.Source).Distinct(StringComparer.Ordinal).ToList();

        text.Append("# What the planner can actually do\n\n");
        text.Append("> Measured on ").Append(when.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture))
            .Append(", on ").Append(measurements.Select(m => m.Scenario.Id).Distinct(StringComparer.Ordinal).Count())
            .Append(" controlled scenarios against our own demo shop, ").Append(repetitions)
            .Append(" execution(s) each. Generated by `tools/Testo.Benchmark`.\n\n");

        if (sources.Count == 1 && sources.Contains("baseline", StringComparer.Ordinal))
        {
            // Said at the top, in the first thing a reader sees, because a table with one column
            // invites being read as though the missing column had been measured and found equal.
            text.Append(
                """
                > **There is no planner column in this run.** No model API key was configured, so what
                > follows measures only the hand-written baseline. It establishes that the scenarios,
                > the defects and the executor behave, which is what the planner will be compared
                > against — and it says nothing whatever about what a model can do. Until a run with a
                > planner appears here, no claim about AI-found defects is supported by anything.
                >
                > To fill it in: `PLANNER__APIKEY=... dotnet run --project tools/Testo.Benchmark`.

                """).Append('\n');
        }

        text.Append(Preamble());

        text.Append("\n## Summary\n\n");
        text.Append("| | ").Append(string.Join(" | ", sources)).Append(" |\n");
        text.Append("|---|").Append(string.Join("|", sources.Select(_ => "---"))).Append("|\n");

        Row(text, "Runs", sources, measurements, group => group.Sum(m => m.Attempts.Count).ToString(CultureInfo.InvariantCulture));
        Row(text, "**False positives** (passed a broken shop)", sources, measurements, group => Count(group, Verdict.FalsePositive));
        Row(text, "False negatives (failed a sound shop)", sources, measurements, group => Count(group, Verdict.FalseNegative));
        Row(text, "Correct verdicts", sources, measurements, group => Count(group, Verdict.Correct));
        Row(text, "Failed the broken shop *and* the sound one", sources, measurements, group => Count(group, Verdict.FailedRegardless));
        Row(text, "Never reached a verdict", sources, measurements, group => Count(group, Verdict.Inconclusive));
        Row(text, "Scenarios that flaked", sources, measurements, group => group.Count(m => m.Flaked).ToString(CultureInfo.InvariantCulture));
        Row(text, "Could not be planned", sources, measurements, group => group.Count(m => m.PlanningErrors.Count > 0).ToString(CultureInfo.InvariantCulture));
        Row(text, "Median execution", sources, measurements, Median);
        Row(text, "Tokens per planned run", sources, measurements, group => Tokens(group));
        Row(text, "Cost per planned run", sources, measurements, group => Cost(group));

        text.Append("\n## Every scenario\n\n");
        text.Append("| Scenario | Defect | Source | Verdict | Status | Flaked | Execution | Tokens | Cost |\n");
        text.Append("|---|---|---|---|---|---|---|---|---|\n");

        foreach (var measurement in measurements)
        {
            text.Append("| ").Append(measurement.Scenario.Id);
            text.Append(" | ").Append(measurement.DefectOn ? "**on**" : "off");
            text.Append(" | ").Append(measurement.Source);
            text.Append(" | ").Append(measurement.PlanningErrors.Count > 0 ? "no plan" : Word(measurement.Verdict));
            text.Append(" | ").Append(measurement.Attempts.Count > 0 ? measurement.Attempts[0].Status.ToString() : "—");
            text.Append(" | ").Append(measurement.Flaked ? "yes" : "no");
            text.Append(" | ").Append(measurement.Attempts.Count > 0
                ? measurement.Average.TotalSeconds.ToString("0.0", CultureInfo.InvariantCulture) + " s"
                : "—");
            text.Append(" | ").Append(measurement.Planning.TotalTokens > 0
                ? measurement.Planning.TotalTokens.ToString(CultureInfo.InvariantCulture)
                : "—");
            text.Append(" | ").Append(measurement.Planning.Cost > 0
                ? "$" + measurement.Planning.Cost.ToString("0.0000", CultureInfo.InvariantCulture)
                : "—");
            text.Append(" |\n");
        }

        var failures = measurements.Where(m => m.PlanningErrors.Count > 0).ToList();

        if (failures.Count > 0)
        {
            text.Append("\n## Plans that were refused\n\n");

            foreach (var measurement in failures)
            {
                text.Append("- **").Append(measurement.Scenario.Id).Append("** (")
                    .Append(measurement.Source).Append("): ")
                    .Append(string.Join(", ", measurement.PlanningErrors.Select(Explain))).Append('\n');
            }
        }

        var noted = measurements.Where(m => m.Notes.Count > 0).ToList();

        if (noted.Count > 0)
        {
            text.Append("\n## What the planner and the validator had to say\n\n");

            foreach (var measurement in noted)
            {
                foreach (var note in measurement.Notes)
                {
                    text.Append("- **").Append(measurement.Scenario.Id).Append("**: ").Append(note).Append('\n');
                }
            }
        }

        return text.ToString();
    }

    private static string Preamble() =>
        """
        ## How to read this

        **The baseline is a plan a person wrote**, in the same vocabulary, run by the same executor.
        So the only difference between the columns is who chose the actions. A baseline written as
        Playwright code would also differ in how it waits and how it locates, and the table would be
        comparing two things at once.

        Six of the scenarios have a real defect in the shop that they are meant to catch, and they run
        twice: once against a sound shop, where passing is correct, and once with the defect switched
        on, where **passing is a false positive**. The other six only run against a sound shop, and
        measure the opposite mistake.

        The asymmetry between the two mistakes is the whole point of measuring. A false negative costs
        a person an afternoon. A false positive converts an absence of testing into an assurance of
        quality, which is worse than having no tests at all, because somebody then ships on it.

        **"Detected nothing" is a third outcome, and it exists because the first real measurement
        needed it.** A plan that fails the broken shop *and* the sound one has not found the defect;
        it fails at everything, and one of the things it fails at happens to be broken. Counting
        those as correct verdicts turned "one defect genuinely caught out of six" into "five of six",
        which is the sort of number a benchmark exists to prevent.

        Flake is measured across repeated **executions** of the same plan, so it describes the
        application and our runner, not the model's variation between answers. That is a different
        question and it is not answered here.

        """;

    private static void Row(
        StringBuilder text,
        string label,
        IReadOnlyList<string> sources,
        IReadOnlyList<Measurement> measurements,
        Func<IReadOnlyList<Measurement>, string> value)
    {
        text.Append("| ").Append(label);

        foreach (var source in sources)
        {
            var group = measurements.Where(m => string.Equals(m.Source, source, StringComparison.Ordinal)).ToList();
            text.Append(" | ").Append(value(group));
        }

        text.Append(" |\n");
    }

    private static string Count(IReadOnlyList<Measurement> group, Verdict verdict) =>
        group.SelectMany(m => m.Attempts).Count(attempt => attempt.Verdict == verdict).ToString(CultureInfo.InvariantCulture);

    private static string Median(IReadOnlyList<Measurement> group)
    {
        var times = group.SelectMany(m => m.Attempts).Select(a => a.Elapsed.TotalSeconds).Order().ToList();

        return times.Count == 0
            ? "—"
            : times[times.Count / 2].ToString("0.0", CultureInfo.InvariantCulture) + " s";
    }

    private static string Tokens(IReadOnlyList<Measurement> group)
    {
        var planned = group.Where(m => m.Planning.Attempts > 0).ToList();

        return planned.Count == 0
            ? "—"
            : ((int)planned.Average(m => m.Planning.TotalTokens)).ToString(CultureInfo.InvariantCulture);
    }

    private static string Cost(IReadOnlyList<Measurement> group)
    {
        var planned = group.Where(m => m.Planning.Attempts > 0).ToList();

        return planned.Count == 0 || planned.All(m => m.Planning.Cost == 0)
            ? "—"
            : "$" + planned.Average(m => m.Planning.Cost).ToString("0.0000", CultureInfo.InvariantCulture);
    }

    private static string Word(Verdict verdict) => verdict switch
    {
        Verdict.Correct => "correct",
        Verdict.FalsePositive => "**false positive**",
        Verdict.FalseNegative => "false negative",
        Verdict.FailedRegardless => "detected nothing",
        _ => "inconclusive",
    };

    private static string Explain(string error) => error switch
    {
        PlanningErrors.NoPlanner => "no planner configured",
        PlanningErrors.ProviderUnavailable => "the provider could not be reached",
        PlanningErrors.ProviderRefusedTheKey => "the provider refused the key (401 or 403): it is wrong, truncated, expired or revoked",
        PlanningErrors.Unreadable => "the answer was not a plan",
        PlanningErrors.ForeignOrigin => "a path named somewhere other than the shop",
        PlanningErrors.NoAssertions => "the plan checked nothing",
        PlanningErrors.TooManyActions => "the plan was longer than the budget",
        PlanningErrors.UnknownAction => "the plan used an action that does not exist",
        PlanningErrors.UnknownTarget => "a target was named in a way that is not allowed",
        PlanningErrors.Incomplete => "an action was missing something it needs",
        PlanningErrors.BudgetSpent => "planning spent the run's token or money budget",
        _ => error,
    };
}
